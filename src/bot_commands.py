def telegram_api(token, method, fields, timeout=35):
    data = urllib.parse.urlencode(fields).encode("utf-8")
    request = urllib.request.Request(
        "https://api.telegram.org/bot" + token + "/" + method,
        data=data, headers={"Content-Type": "application/x-www-form-urlencoded"}, method="POST"
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        payload = json.load(response)
    if not payload.get("ok"):
        raise RuntimeError("Telegram API returned not-ok")
    return payload["result"]


def open_readonly(db_path):
    con = sqlite3.connect("file:" + urllib.parse.quote(db_path, safe="/") + "?mode=ro",
                          uri=True, timeout=5)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA busy_timeout=5000")
    return con


def time_label(epoch):
    return dt.datetime.fromtimestamp(int(epoch), tz=UTC).strftime("%m-%d %H:%M UTC")


def escaped_prefix(value, limit):
    parts = []
    size = 0
    for char in value or "":
        escaped = html.escape(char, quote=True)
        if size + len(escaped) > limit:
            break
        parts.append(escaped)
        size += len(escaped)
    return "".join(parts)


def heartbeat_message(db_path, heartbeat, sources, now):
    tick = int(heartbeat.get("last_tick") or 0)
    started = int(heartbeat.get("started") or now)
    age = max(0, now - tick) if tick else None
    state = "运行中" if age is not None and age < 180 else "循环延迟"
    with contextlib.closing(open_readonly(db_path)) as con:
        source_rows = {r["id"]: r for r in con.execute(
            "SELECT id,seeded,last_ok,last_error FROM sources"
        )}
        row = con.execute(
            "SELECT SUM(status='sent') AS sent, SUM(status='pending') AS pending,"
            " MAX(sent_at) AS last_sent FROM outbox"
        ).fetchone()
    ready = 0
    for source in sources:
        status = source_rows.get(source["id"])
        if not status or not status["seeded"] or not status["last_ok"]:
            continue
        max_age = 4200 if source["id"] == "rsshub_releases" else max(
            1200, int(source.get("interval_seconds", 60)) * 3)
        ready += now - int(status["last_ok"]) <= max_age
    latest = time_label(row["last_sent"]) if row["last_sent"] else "暂无"
    return (f"📟 <b>RSS 进程心跳：{state}</b>\n"
            f"最近循环：{str(age) + ' 秒前' if age is not None else '暂无'}\n"
            f"启动时间：{time_label(started)}\n"
            f"订阅源：{ready}/{len(sources)} 最近更新\n"
            f"新闻：已发 {row['sent'] or 0} · 待发 {row['pending'] or 0}\n"
            f"最近发送：{latest}")


def recent_news_message(db_path):
    with contextlib.closing(open_readonly(db_path)) as con:
        rows = con.execute(
            """SELECT e.title,e.source,e.link,e.priority,o.sent_at
               FROM outbox o JOIN events e ON e.id=o.event_id
               WHERE o.status='sent' AND o.sent_at IS NOT NULL
               ORDER BY o.sent_at DESC,o.id DESC LIMIT 10"""
        ).fetchall()
        if not rows:
            return "📰 暂无已发送的 RSS 新闻。"
        headlines = []
        for row in rows:
            title = row["title"] or ""
            translated = title
            key = hashlib.sha256(("en-zh-v1|" + title).encode("utf-8")).hexdigest()
            try:
                cached = con.execute(
                    "SELECT text_zh FROM translation_cache WHERE input_hash=?", (key,)
                ).fetchone()
                if cached:
                    translated = cached["text_zh"]
            except sqlite3.OperationalError:
                # Collector V3 databases may predate the optional V4 cache.
                pass
            label = escaped_prefix(translated, 125)
            source = escaped_prefix(row["source"], 50)
            link = row["link"] or ""
            safe_link = ""
            try:
                if urllib.parse.urlsplit(link).scheme in ("https", "http"):
                    encoded = html.escape(link, quote=True)
                    if len(encoded) <= 150:
                        safe_link = encoded
            except ValueError:
                pass
            headlines.append((label, safe_link, source, row["priority"], time_label(row["sent_at"])))
    lines = ["📰 <b>最近 10 条已发送 RSS 新闻</b>"]
    for i, (label, link, source, priority, stamp) in enumerate(headlines, 1):
        suffix = f"\n   {html.escape(priority)} · {source} · {stamp}"
        item = f'{i}. <a href="{link}">{label}</a>{suffix}' if link else f"{i}. {label}{suffix}"
        if len("\n".join(lines)) + len(item) + 1 > 3900:
            item = f"{i}. {label}{suffix}"
        lines.append(item)
    return "\n".join(lines)


def help_message(market_db_path):
    hours = 4
    try:
        con = market_store.open_readonly(market_db_path)
        try:
            hours = int(market_store.meta_get(con, "interval_hours", 4) or 4)
        finally:
            con.close()
    except (sqlite3.Error, ValueError):
        pass
    lines = ["🤖 <b>可用命令</b>"] + [f"/{name} {html.escape(text)}" for name, text in COMMAND_MENU if name != "help"]
    lines.append(f"\n⏰ 市场简报每 {hours} 小时自动推送（{market_store.schedule_label(hours)}）。")
    lines.append("命令返回的是最近一次快照（约每 15 分钟更新），回复里会注明数据时间。")
    lines.append("重大异动会实时推送（每天最多 8 条，北京 00–08 点静音）。")
    return "\n".join(lines)


def parse_command(raw, bot_username=None):
    """Return (command, args) or None; '/cmd@OtherBot' addressed elsewhere is ignored."""
    words = raw.strip().split()
    if not words or not words[0].startswith("/"):
        return None
    command, _, target = words[0].partition("@")
    if target and (not bot_username or target.lower() != bot_username.lower()):
        return None
    return command.lower(), [w.lower() for w in words[1:]]


def command_reply(update, authorized_chat_id, db_path, heartbeat, sources, now,
                  market_db_path=MARKET_DB_PATH, bot_username=None):
    """Reply tuple (chat_id, message_id, text-or-list-of-texts) for an authorized command."""
    message = update.get("message") or {}
    chat = message.get("chat") or {}
    if str(chat.get("id")) != str(authorized_chat_id):
        return None
    raw = message.get("text")
    if not isinstance(raw, str):
        return None
    parsed = parse_command(raw, bot_username)
    if parsed is None:
        return None
    command, args = parsed
    if command == "/logs" and not args:
        response = (heartbeat_message(db_path, heartbeat, sources, now) + "\n"
                    + market_store.status_line(market_db_path, now))
    elif command == "/news" and args in ([], ["ago"]):
        response = recent_news_message(db_path)
    elif command in MARKET_VIEWS and not args:
        response = market_store.view_messages(market_db_path, MARKET_VIEWS[command], now)
    elif command == "/q":
        if len(args) != 1:
            response = "用法：/q 代码，例如 /q NVDA、/q SPY 或 /q BTC"
        else:
            response = market_store.quote_messages(market_db_path, args[0], now)
    elif command in ("/help", "/start") and not args:
        response = help_message(market_db_path)
    else:
        return None
    return (chat["id"], message["message_id"], response)


def register_commands(token):
    """Publish the command menu; returns the bot username used for '/cmd@bot' matching."""
    username = None
    try:
        username = telegram_api(token, "getMe", {}, timeout=15).get("username")
        telegram_api(token, "setMyCommands", {"commands": json.dumps(
            [{"command": name, "description": text} for name, text in COMMAND_MENU], ensure_ascii=False)}, timeout=15)
        LOG.info("Telegram command menu registered (%d commands)", len(COMMAND_MENU))
    except Exception as exc:  # best effort: the menu must never stop the command poller
        LOG.warning("Telegram command menu registration failed (%s)", type(exc).__name__)
    return username


def run_command_poller(token, authorized_chat_id, db_path, heartbeat, lock, sources, stop_event, clock):
    """Consume commands only after process startup; never replay older requests."""
    started = clock()
    offset = None
    bot_username = register_commands(token)
    while not stop_event.is_set():
        try:
            fields = {"timeout": 25, "limit": 100, "allowed_updates": '["message"]'}
            if offset is not None:
                fields["offset"] = offset
            updates = telegram_api(token, "getUpdates", fields)
            for update in updates:
                offset = max(offset or 0, int(update["update_id"]) + 1)
                message = update.get("message") or {}
                if int(message.get("date") or 0) < started:
                    continue
                with lock:
                    snapshot = dict(heartbeat)
                try:
                    reply = command_reply(update, authorized_chat_id, db_path, snapshot, sources, clock(),
                                          bot_username=bot_username)
                    if reply:
                        texts = reply[2] if isinstance(reply[2], list) else [reply[2]]
                        for index, text in enumerate(texts):
                            fields = {"chat_id": reply[0], "text": text, "parse_mode": "HTML",
                                      "disable_web_page_preview": "true"}
                            if index == 0:
                                fields["reply_to_message_id"] = reply[1]
                            telegram_api(token, "sendMessage", fields, timeout=15)
                except Exception as exc:
                    # One bad reply (rendering bug, BadStatusLine, read timeout...) must not kill the
                    # poller thread: nothing restarts it and the update is already acknowledged.
                    LOG.warning("command reply failed (%s)", type(exc).__name__)
        except urllib.error.HTTPError as exc:
            if exc.code == 409:
                LOG.warning("Telegram command polling conflict (another consumer or webhook)")
            else:
                LOG.warning("Telegram command polling HTTP %d", exc.code)
            stop_event.wait(30)
        except (ValueError, KeyError, RuntimeError, OSError, http.client.HTTPException) as exc:
            # OSError covers URLError and long-poll read timeouts; HTTPException covers BadStatusLine and
            # IncompleteRead, which urlopen/json.load raise unwrapped. Either would otherwise kill this thread.
            # Never log urllib exception text: it can contain the bot token URL.
            LOG.warning("Telegram command polling failed (%s)", type(exc).__name__)
            stop_event.wait(15)
